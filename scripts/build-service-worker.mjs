/**
 * Build the MV3 service worker as a single classic script:
 * vendor/focusbuddy-auth.iife.js + background.js
 *
 * Chrome can fail with "An unknown error occurred when fetching the script"
 * when the SW importScripts() a large nested vendor file — inlining avoids that.
 */
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.join(root, "..");

execSync("npm run build:extension-auth", { cwd: repoRoot, stdio: "inherit" });

const authPath = path.join(repoRoot, "vendor/focusbuddy-auth.iife.js");
const backgroundPath = path.join(repoRoot, "background.js");
const outPath = path.join(repoRoot, "service-worker.js");

const auth = fs.readFileSync(authPath, "utf8");
const background = fs.readFileSync(backgroundPath, "utf8");

const banner = `/* Generated by scripts/build-service-worker.mjs — do not edit.
 * Sources: vendor/focusbuddy-auth.iife.js + background.js
 * Rebuild: npm run build:extension
 */
`;

fs.writeFileSync(outPath, `${banner}${auth}\n${background}`);
console.log(
  `Wrote ${path.relative(repoRoot, outPath)} (${fs.statSync(outPath).size} bytes)`
);
